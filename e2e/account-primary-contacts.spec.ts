test("scoped 403/ordinary contact errors preserve names, Retry touches only failed contact", async ({ page }) => {
  const reads = await mockContacts(page, { Email: { status: 403, body: {} }, Mobile: { status: 500, body: {} } })
  const bodies = await mockUserEdit(page, { status: 204 })
  await page.goto("/account")
  await section(page).getByRole("button", { name: "Edit", exact: true }).click()
  await expect(section(page).getByText("You don't have access to this in your current account", { exact: true })).toBeVisible()
  await expect(section(page).getByText("Something went wrong while loading profile information", { exact: true })).toBeVisible()
  await expect(email(page)).toHaveCount(0)
  const emailReads = reads.filter((type) => type === "Email").length
  await section(page).getByRole("button", { name: "Retry", exact: true }).click()
  await expect.poll(() => reads.filter((type) => type === "Mobile").length).toBeGreaterThan(1)
  expect(reads.filter((type) => type === "Email")).toHaveLength(emailReads)
  await section(page).getByRole("textbox", { name: "First name", exact: true }).fill("Bea")
  await save(page)
  await expect(section(page).getByRole("button", { name: "Edit", exact: true })).toBeVisible()
  expect(bodies()).toEqual([{ firstName: "Bea" }])
})

import AxeBuilder from "@axe-core/playwright"
import { expect, type Page } from "@playwright/test"
import { test, mockAccountDefaults, mockMyself, mockContacts, mockProxy, mockAddresses, mockUserEdit, mockAccountTimeZone, ACCOUNT_SETTINGS_MYSELF, ACCOUNT_PRIMARY_CONTACTS, signIn, setTheme } from "./fixtures"
const section = (page: Page) => page.getByRole("region", { name: "Personal account settings", exact: true })
const email = (page: Page) => section(page).getByRole("combobox", { name: "Primary email address", exact: true })
const phone = (page: Page) => section(page).getByRole("combobox", { name: "Primary phone number", exact: true })
const save = (page: Page) => section(page).getByRole("button", { name: "Save", exact: true }).click()
async function edit(page: Page) {
  await page.goto("/account")
  await section(page).getByRole("button", { name: "Edit", exact: true }).click()
  await expect(email(page)).not.toHaveAttribute("aria-busy", "true")
  await expect(phone(page)).not.toHaveAttribute("aria-busy", "true")
}
async function choose(page: Page, kind: "email" | "phone") {
  await (kind === "email" ? email(page) : phone(page)).click()
  await page.getByRole("option", { name: kind === "email" ? "ann.work@example.test" : "+44 20 7183 8750", exact: true }).click()
}
test.beforeEach(async ({ page }) => {
  await mockAccountDefaults(page)
  await mockMyself(page, { body: ACCOUNT_SETTINGS_MYSELF })
  await mockContacts(page, ACCOUNT_PRIMARY_CONTACTS)
  await signIn(page)
})
for (const theme of ["light", "dark"] as const) {
  test(`UJ-101 changes verified Email/Mobile, notices and header in ${theme}`, async ({ page }) => {
    let current = { ...ACCOUNT_SETTINGS_MYSELF }
    let selected = false
    await mockProxy(page, "v2/user/contact-point/list?**", (request) => {
      const type = new URL(request.url()).searchParams.get("type")
      const rows = type === "Email" ? ACCOUNT_PRIMARY_CONTACTS.Email : type === "Mobile" ? ACCOUNT_PRIMARY_CONTACTS.Mobile : []
      return { body: rows.map((row) => ({ ...row, label: selected ? row.value === "ann.work@example.test" || row.value === "+442071838750" ? "Primary" : "Old" : "label" in row ? row.label : null })) }
    })
    await mockProxy(page, "v2/user/myself", () => ({ body: current }))
    const bodies = await mockUserEdit(page, (request) => {
      const body = request.postDataJSON()
      current = { ...current, email: body.email, phoneNumber: body.phoneNumber }
      selected = true
      return { status: 204 }
    })
    await edit(page)
    await setTheme(page, theme)
    await email(page).click()
    await expect(page.getByRole("option")).toHaveCount(2)
    await expect(page.getByRole("option", { name: "ann.lee@example.test", exact: true })).toHaveAttribute("aria-selected", "true")
    expect((await new AxeBuilder({ page }).include('[role="listbox"]').withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([])
    await page.getByRole("option", { name: "ann.work@example.test", exact: true }).click()
    await choose(page, "phone")
    await expect(section(page).getByText("Changing your primary email will result in updating your login credentials. The next time you login you will have to use the new email.", { exact: true })).toBeVisible()
    await expect(section(page).getByText("Changing your primary phone will result in updating your notification preferences.", { exact: true })).toBeVisible()
    // Responsive table cells remount, while notice ownership stays with the Section.
    await page.setViewportSize({ width: 360, height: 740 })
    await expect(section(page).getByText(/Changing your primary email/)).toBeVisible()
    expect((await new AxeBuilder({ page }).include("#account").withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([])
    await save(page)
    await expect(page.getByText("Personal account updated successfully", { exact: true })).toBeVisible()
    expect(bodies()).toEqual([{ email: "ann.work@example.test", phoneNumber: "+442071838750", phoneNumberRegion: "GB" }])
    await expect(section(page).getByText("ann.work@example.test", { exact: true })).toBeVisible()
    await page.setViewportSize({ width: 1280, height: 900 })
    await expect(page.getByText("ann.work@example.test", { exact: true })).toHaveCount(2)
    await expect(section(page).getByText(/Changing your primary/)).toHaveCount(0)
  })
}

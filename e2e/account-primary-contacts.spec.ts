test("one cold-cache Restore resolves choices; removed drafted choice falls back to current", async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 740 })
  await edit(page)
  await choose(page, "email")
  await choose(page, "phone")
  await section(page).getByRole("textbox", { name: "First name", exact: true }).fill("Bea")
  await expect.poll(() => page.evaluate(() => Object.values(localStorage).some((value) => value.includes("ann.work@example.test")))).toBe(true)
  const seen = await mockContacts(page, { ...ACCOUNT_PRIMARY_CONTACTS, Email: [] })
  await page.reload()
  await expect(section(page).getByRole("button", { name: "Restore", exact: true })).toBeVisible()
  expect(seen).toEqual([])
  await section(page).getByRole("button", { name: "Restore", exact: true }).click()
  await expect(section(page).getByRole("textbox", { name: "First name", exact: true })).toHaveValue("Bea")
  await expect(email(page)).toHaveText("ann.lee@example.test")
  await expect(phone(page)).toHaveText("+44 20 7183 8750")
  expect(seen.toSorted()).toEqual(["Email", "Mobile"])
})
